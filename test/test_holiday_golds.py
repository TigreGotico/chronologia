def _reg(country, subdiv, name, *ymd):
    HOLIDAY_GOLDS.setdefault((country, subdiv, name), set()).add(ymd)


def _dates_for(country, year, subdiv=None):
    return {(h.name, h.subdiv): h.date for h in holidays_for(country, year, subdiv)}


