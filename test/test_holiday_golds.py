"""Standing-rule backfill: every holiday_data/*.tab rule gets its own gold.

Convention for parallel agents (UK/DE/FR/ES/BR/CA/AU/IN/CN/JP/TR/IL golds land
on other branches and merge later)
--------------------------------------------------------------------------
``HOLIDAY_GOLDS`` is a module-level ``dict`` keyed ``(country, subdiv, name)``
-> a set of ``(year, month, day)`` triples that ``holidays_for`` must produce
for that rule (a rule may resolve to more than one date in a year, e.g. a
``calendar_date`` rule near a lunar-year boundary, or none, per calendar
range rules -- register every year you assert). ``country`` is the upper-case
jurisdiction code (``"PT"``), ``subdiv`` is ``None`` for a jurisdiction-wide
rule or the exact subdivision code from the ``.tab`` file, and ``name`` is the
rule's exact ``name`` column. Register your country's golds into this same
dict (import it from this module and update it at import time, the same way
the PT/US/SA sections below do) so ``test_every_tab_rule_has_a_gold`` -- the
structural enforcement test -- can find them. That test only enforces
jurisdictions for which a ``holiday_data/<cc>.tab`` file is actually present
in this checkout, so an unmerged branch adding e.g. ``de.tab`` + its golds in
the same PR never conflicts with another branch's unmerged ``fr.tab``.

Sourcing discipline
--------------------
* US: every federal entry, including both observed-shift variants, dated from
  the OPM/Wikipedia list already cited in the ``.tab`` header and mirrored at
  ``papers/holidays/us_federal_holidays_wikipedia.html``; the shift itself
  follows 5 U.S.C. 6103 (Sat -> preceding Fri, Sun -> following Mon).
* SA: every entry. The two fixed (Gregorian) days come straight from the
  cited Wikipedia page. The six Islamic days are NOT taken from the engine's
  own ``CalendarDateRule`` conversion -- they are independently re-derived
  here from the raw ``jdn_start`` column of
  ``chronologia/calendar_data/umm_al_qura.tab`` (AH 1445 Shawwal/Dhu
  al-Hijjah) through a standalone Fliegel-van Flandern JDN->Gregorian
  formula that imports nothing from ``chronologia`` -- so this file, not the
  engine, is the independent witness. The result (Eid al-Fitr 2024-04-10,
  Eid al-Adha 2024-06-16) also matches the publicly known 2024 Hijri
  calendar.
* PT national + regional: hand golds, movable ones derived in-test via
  ``easter(2024)`` + the documented Codigo do Trabalho offset.
* PT municipal (fixed, ~224 entries -- the bulk): NOT hand-typed. Golds are
  generated by parsing the cited seed
  ``papers/holidays/feriados.tsv`` (date + municipality names) and
  ``papers/holidays/municipios_portugal.csv`` (municipality name -> ISO
  subdivision code), then cross-checked one-for-one against every
  ``fixed ... municipal`` row of ``pt.tab``. This is source-vs-engine: the
  expected date comes from the TSV text, not from the ``.tab`` file's own
  ``args`` column.
* PT municipal (movable, ~73 entries): golds are generated by parsing
  ``papers/holidays/feriados_moveis.tsv``'s Portuguese date phrases
  ("Segunda-feira apos a Pascoa", "Segunda-feira apos o segundo Domingo de
  Julho", ...) through a small hand-written phrase -> rule mapping table
  (mirrored from the documented conversions in that file, not copied from
  ``pt.tab``), evaluated against ``easter(2024)`` / the RRULE nth-weekday
  engine, and cross-checked against ``pt.tab``'s ``easter``/``nth_weekday``
  rows. Two phrase-mapping bugs were caught and fixed against this
  independent derivation while building this file (see "Disagreements
  found" below) -- both turned out to be errors in the phrase table, not in
  ``pt.tab``, once resolved carefully; see the module docstring further
  below for the one thing that *did* warrant a closer look.

Disagreements found while building this backfill
--------------------------------------------------------------------------
None that survive: two apparent PT movable-municipal mismatches surfaced
during authoring (Ponta Delgada's "Senhor Santo Cristo dos Milagres" and
Vieira do Minho's "Feira da Ladra") but both traced back to this file's own
first-draft phrase table -- "Quinta Segunda-feira" is the *fifth* Monday
after Easter (Portuguese ordinal quinta = 5th, not 4th), and "the Monday
after the first Saturday of October" is two days after that Saturday, not
one. With the phrase table corrected, all 224 fixed + 73 movable PT
municipal rows agree with the source TSVs, and the source TSVs' own
municipality-name spellings needed a small alias table (Madeira/Acores
disambiguating suffixes, accents, "Praia da Vitoria" -> "Vila da Praia da
Vitoria") to line up with ``municipios_portugal.csv``'s codes -- listed
inline below, not silently dropped.
"""
