@pytest.mark.parametrize("day,monw,mon,year", _CASES)
def test_full_date(day, monw, mon, year):
    phrase = f"{day} de {monw} de {year}"
    s, e = start_end(phrase)
    d0 = datetime(year, mon, day)
    assert s == ad(d0)
    assert e == ad(d0 + timedelta(days=1))
    assert parse(phrase)[1] == ""
