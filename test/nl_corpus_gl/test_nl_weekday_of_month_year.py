def nth_weekday(year, month, weekday, n):
    """The day-of-month of the ``n``-th ``weekday`` (0=Mon) of a month, or the
    last one when ``n == "last"``.  Parser-independent gold."""
    days = [d for d in range(1, calendar.monthrange(year, month)[1] + 1)
            if datetime(year, month, d).weekday() == weekday]
    return days[-1] if n == "last" else days[n - 1]


