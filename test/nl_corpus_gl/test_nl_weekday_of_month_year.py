"""Higher-ordinal "o <Nth> <weekday> de <month> <year>" sweep for Galician.

Romance higher-ordinals bind the weekday after the number-fold fix, and a bare
trailing year ("... de marzo 2020") pins the calendar year -- so the whole
"Nth weekday of a named month in a given year" construction resolves to one
exact calendar day.  The gold day is derived by independent calendar
arithmetic (:func:`nth_weekday`), never by the parser: we enumerate the real
weekdays of the target month and index them.  Anchor is Tuesday 2017-06-27.
"""
import calendar
